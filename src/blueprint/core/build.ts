import { compileBlueprint, jsLiteral, type CompileOptions, type CompiledBlueprint } from './compile';
import { HELPERS, resolveHelpers } from './helpers';
import type { NodeRegistry } from './registry';
import type { Blueprint, Diagnostic } from './types';

export interface BuildOptions extends CompileOptions {
  /**
   * `page` (default): a self-starting script for a page (runs on DOMContentLoaded).
   * `preview`: an expression evaluating to `function start(document) → dispose`, used by the
   * editor to run blueprints in the canvas and stop them again.
   */
  target?: 'page' | 'preview';
  /** Include disabled blueprints (default false). */
  includeDisabled?: boolean;
  /** Banner comment (default: generated-by note; `false` for none). */
  banner?: string | false;
}

export interface BuildResult {
  code: string;
  /** Compiled blueprints included in the output. */
  blueprints: CompiledBlueprint[];
  diagnostics: (Diagnostic & { blueprintId: string })[];
  /** True when any blueprint has errors (it is still included, with the broken parts left out). */
  hasErrors: boolean;
}

export const DEFAULT_BANNER = 'Generated by grapesjs-scripts from blueprints. Edit the blueprints, not this file.';

/** Combines global and template blueprints into one script. Component blueprints are skipped. */
export function buildScript(blueprints: Blueprint[], registry: NodeRegistry, options: BuildOptions = {}): BuildResult {
  const u = options.indent ?? '  ';
  const list = blueprints.filter((b) => b && b.kind !== 'component' && (options.includeDisabled || b.enabled !== false));
  const compiled = list.map((b) => compileBlueprint(b, registry, options));
  const helpers = resolveHelpers(new Set(compiled.flatMap((c) => c.helpers)));
  const diagnostics = compiled.flatMap((c) => c.diagnostics.map((d) => ({ ...d, blueprintId: c.id })));

  const entries = compiled.map((c, i) => {
    const when = list[i].kind === 'template' ? list[i].target?.when?.trim() || null : null;
    return `{ id: ${jsLiteral(c.id)}, when: ${jsLiteral(when)}, run: ${indentRest(c.code, u)} }`;
  });

  const start = [
    'function start(doc) {',
    `${u}var stops = [];`,
    `${u}blueprints.forEach(function (b) {`,
    `${u}${u}try {`,
    `${u}${u}${u}if (b.when && !doc.querySelector(b.when)) return;`,
    `${u}${u}${u}var stop = b.run(doc, {});`,
    `${u}${u}${u}if (typeof stop === 'function') stops.push(stop);`,
    `${u}${u}} catch (e) {`,
    `${u}${u}${u}if (typeof console !== 'undefined') console.error('[blueprint ' + b.id + ']', e);`,
    `${u}${u}}`,
    `${u}});`,
    `${u}return function () { stops.splice(0).forEach(function (s) { try { s(); } catch (e) {} }); };`,
    '}',
  ].join('\n');

  // Blueprints first (what the reader is after), runtime helpers below them: they are function
  // declarations (hoisted) or set before `start` runs.
  const inner = [
    "'use strict';",
    entries.length ? `var blueprints = [\n${entries.map((e) => u + e).join(',\n')}\n];` : 'var blueprints = [];',
    start,
    ...(helpers.length ? ['// Runtime helpers', ...helpers.map((h) => HELPERS[h].code)] : []),
  ];

  let code: string;
  if (options.target === 'preview') {
    code = `(function () {\n${indent([...inner, 'return start;'].join('\n'), u)}\n})()`;
  } else {
    inner.push(
      "if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', function () { start(document); });",
      'else start(document);',
    );
    code = `(function () {\n${indent(inner.join('\n'), u)}\n})();\n`;
  }
  const banner = options.banner === false ? '' : `/* ${(options.banner ?? DEFAULT_BANNER).replace(/\*\//g, '* /')} */\n`;
  return {
    code: banner + code,
    blueprints: compiled,
    diagnostics,
    hasErrors: diagnostics.some((d) => d.severity === 'error'),
  };
}

function indent(code: string, u: string): string {
  return code
    .split('\n')
    .map((l) => (l.trim() ? u + l : l))
    .join('\n');
}

/** Indents every line but the first (for values placed after `key: `). */
function indentRest(code: string, u: string): string {
  const [first, ...rest] = code.split('\n');
  return [first, ...rest.map((l) => (l.trim() ? u + l : l))].join('\n');
}

/**
 * A self-contained function expression `function (root, ctx) → dispose` for one blueprint,
 * helpers included. Used for component blueprints (one function per component type).
 */
export function buildStandalone(bp: Blueprint, registry: NodeRegistry, options: CompileOptions = {}): CompiledBlueprint {
  const u = options.indent ?? '  ';
  const compiled = compileBlueprint(bp, registry, options);
  const helpers = resolveHelpers(compiled.helpers);
  const inner = [...helpers.map((h) => HELPERS[h].code), `return (${indentRest(compiled.code, '')})(root, ctx);`].join('\n');
  return { ...compiled, code: `function (root, ctx) {\n${indent(inner, u)}\n}` };
}
